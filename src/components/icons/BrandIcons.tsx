export function getSocialIcon(name: string) {
  switch (name.toLowerCase()) {
    case "github":
      return GithubIcon;
    case "discord":
      return DiscordIcon;
    case "curseforge":
      return CurseForgeIcon;
    case "modrinth":
      return ModrinthIcon;
    case "youtube":
      return YoutubeIcon;
    case "x (twitter)":
    case "twitter":
    case "x":
      return XTwitterIcon;
    case "instagram":
      return InstagramIcon;
    case "threads":
      return ThreadsIcon;
    default:
      return GithubIcon;
  }
}
